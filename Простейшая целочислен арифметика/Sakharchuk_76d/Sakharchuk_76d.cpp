//Поле шахматной доски определяется парой натуральных чисел, каждое из которых не превосходит 8: 
//первое число - номер вертикали(при счете сле - ва направо), второе : номер горизонтали(при счете снизу вверх).
//Даны натуральные числа k, l, m, n, каждое из которых не превосходит 8. 
//Требуется :
//Аналогично г), но ладья заменяется на ферзя.
//Контрольный пример 1:
//Исходные данные : k = 2, l = 2, m = 4, n = 2
//Ожидаемый результат : Можно
//Контрольный пример 2 :
//Исходные данные : k = 2, l = 2, m = 4, n = 3
//Ожидаемый результат : Промежуточный ход(2; 3) или(4; 2) или(2; 4), или(3; 3), или(4; 5), или(5; 3)

#include <iostream>
#include <cmath>

using namespace std;

bool canQueenMove(int x1, int y1, int x2, int y2) {
    if (x1 == x2 && y1 == y2) return false;
    return (x1 == x2) || (y1 == y2) || (abs(x1 - x2) == abs(y1 - y2));
}

int main() {
    setlocale(LC_ALL, "");

    int k, l, m, n;
    cin >> k >> l >> m >> n;

    if (canQueenMove(k, l, m, n)) {
        cout << "Можно" << endl;
    }
    else {
        cout << "Промежуточный ход ";
        bool first = true;

        for (int x = 1; x <= 8; ++x) {
            for (int y = 1; y <= 8; ++y) {
                if (canQueenMove(k, l, x, y) && canQueenMove(x, y, m, n)) {
                    if (!first) {
                        cout << " или ";
                    }
                    cout << "(" << x << ";" << y << ")";
                    first = false;
                }
            }
        }
        cout << endl;
    }

    return 0;
}
